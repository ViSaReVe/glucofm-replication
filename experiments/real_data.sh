#!/usr/bin/env bash
#
# End-to-end real-data experiment: pretrain on ShanghaiT2DM, evaluate
# subject-disjoint on CGMacros. Covers subject partitioning, preparation,
# training, probing and aggregation with fixed seeds.
#
# Data is NOT downloaded here and is not redistributed with this repository.
# Fetch both cohorts yourself first; see docs/datasets.md for sources, licences
# and checksums.
#
#   ./experiments/real_data.sh <shanghai-root> <cgmacros-root> <output-dir>
#
# Provenance -- input hashes, package versions and the git commit -- is written
# into <output-dir>/aggregate.json by the final step.
#
# ---------------------------------------------------------------------------
# THIS DOES NOT REPRODUCE THE RECORDED 2026-09-07 RESULTS, BY DESIGN.
#
# That run prepared the whole cohort with overlapping sampling and split the
# windowed NPZ, which forced overlapping windows onto the validation partition
# too. This script partitions by subject *before* windowing, so validation is
# non-overlapping as docs/implementation-decisions.md assumption 11 requires.
# Set LEGACY_VALIDATION=1 to reproduce the recorded run's partitioning instead.
#
# Either way, pretraining is stochastic across BLAS versions and thread counts;
# expect close, not identical, numbers. reports/real-data.md is the record of
# the original run and is not regenerated by this script.
# ---------------------------------------------------------------------------

set -euo pipefail

SHANGHAI_ROOT=${1:?usage: real_data.sh <shanghai-root> <cgmacros-root> <output-dir>}
CGMACROS_ROOT=${2:?usage: real_data.sh <shanghai-root> <cgmacros-root> <output-dir>}
OUT=${3:?usage: real_data.sh <shanghai-root> <cgmacros-root> <output-dir>}

SEEDS=${SEEDS:-"42 43 44"}          # pretraining initialisations
PARTITION_SEED=${PARTITION_SEED:-0} # subject split
SAMPLING_SEED=${SAMPLING_SEED:-0}   # overlapping-window strides
VALIDATION_FRACTION=${VALIDATION_FRACTION:-0.2}
EPOCHS=${EPOCHS:-120}
BATCH_SIZE=${BATCH_SIZE:-128}
FOLDS=${FOLDS:-5}
REPEATS=${REPEATS:-10}
THREADS=${THREADS:-2}
RECOVERY=${RECOVERY:-slope-change}  # CGMacros mask policy; see docs/datasets.md
LEGACY_VALIDATION=${LEGACY_VALIDATION:-0}
SENSORS=${SENSORS:-"dexcom libre"}
LABELS=${LABELS:-"diabetes insulin_resistance hyperlipidemia obesity"}

mkdir -p "$OUT"/{canonical,prepared,runs,probes}
glucofm() { python -m glucofm.cli --threads "$THREADS" "$@"; }

echo "== 1. Convert cohorts to the canonical schema =="
glucofm convert --dataset shanghai --root "$SHANGHAI_ROOT" --cohort T2DM \
  --output "$OUT/canonical/shanghai-t2dm.csv"

for sensor in $SENSORS; do
  for label in $LABELS; do
    glucofm convert --dataset cgmacros --root "$CGMACROS_ROOT" \
      --sensor "$sensor" --label "$label" --recovery "$RECOVERY" \
      --output "$OUT/canonical/cgmacros-$sensor-$label.csv"
  done
done

echo "== 2. Partition pretraining subjects, then prepare each side =="
if [ "$LEGACY_VALIDATION" = "1" ]; then
  # The recorded run: window everything overlapping, then split the NPZ. Both
  # sides end up overlapping. Kept so the original run stays reproducible.
  glucofm prepare --csv "$OUT/canonical/shanghai-t2dm.csv" \
    --output "$OUT/prepared/shanghai-all.npz" \
    --sampling pretraining --sampling-seed "$SAMPLING_SEED"
  glucofm split --data "$OUT/prepared/shanghai-all.npz" \
    --output-a "$OUT/prepared/pretrain.npz" \
    --output-b "$OUT/prepared/validation.npz" \
    --fraction-b "$VALIDATION_FRACTION" --seed "$PARTITION_SEED"
else
  glucofm partition --csv "$OUT/canonical/shanghai-t2dm.csv" \
    --output-a "$OUT/canonical/shanghai-pretrain.csv" \
    --output-b "$OUT/canonical/shanghai-validation.csv" \
    --fraction-b "$VALIDATION_FRACTION" --seed "$PARTITION_SEED"
  # Overlapping windows for pretraining (Appendix A.2); non-overlapping for the
  # monitoring set, so its loss is not averaged over near-duplicate windows.
  glucofm prepare --csv "$OUT/canonical/shanghai-pretrain.csv" \
    --output "$OUT/prepared/pretrain.npz" \
    --sampling pretraining --sampling-seed "$SAMPLING_SEED"
  glucofm prepare --csv "$OUT/canonical/shanghai-validation.csv" \
    --output "$OUT/prepared/validation.npz" --sampling non-overlapping
fi

# Downstream partitions are always non-overlapping: CV folds are cut from them.
for sensor in $SENSORS; do
  for label in $LABELS; do
    glucofm prepare --csv "$OUT/canonical/cgmacros-$sensor-$label.csv" \
      --output "$OUT/prepared/cgmacros-$sensor-$label.npz" --sampling non-overlapping
  done
done

echo "== 3. Pretrain, one run per seed =="
for seed in $SEEDS; do
  glucofm pretrain --train "$OUT/prepared/pretrain.npz" \
    --validation "$OUT/prepared/validation.npz" --output "$OUT/runs/seed$seed" \
    --epochs "$EPOCHS" --batch-size "$BATCH_SIZE" --seed "$seed" \
    | tee "$OUT/runs/seed$seed.log"
done

echo "== 4. Probe every partition from every checkpoint =="
# Checkpoint selection is keep-last, so last.pt is the selected checkpoint.
# `probe` refuses any overlap between pretraining and downstream subjects.
for seed in $SEEDS; do
  for sensor in $SENSORS; do
    for label in $LABELS; do
      glucofm probe --checkpoint "$OUT/runs/seed$seed/last.pt" \
        --data "$OUT/prepared/cgmacros-$sensor-$label.npz" \
        --folds "$FOLDS" --repeats "$REPEATS" \
        --output "$OUT/probes/${sensor}_${label}.seed${seed}.json" > /dev/null
      echo "  probed seed=$seed sensor=$sensor label=$label"
    done
  done
done

echo "== 5. Aggregate, with provenance =="
glucofm aggregate --probes "$OUT/probes" --output "$OUT/aggregate.json" \
  --provenance "$OUT/prepared"/*.npz

echo
echo "Done. Aggregate: $OUT/aggregate.json"
echo "Spread reported there is across pretraining seeds, not across folds:"
echo "repeated folds over one small subject pool are dependent, so fold-level"
echo "intervals would be far too narrow to mean anything."
